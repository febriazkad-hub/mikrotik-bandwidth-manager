from typing import Tuple
from app.firewall_helper import FirewallHelper

class UninstallHelper:
    """Provides a safe 1-click Clean Detach / Uninstall flow for MikroTik RouterOS"""

    @classmethod
    async def clean_detach(cls, exec_cmd_func, parent_name: str = "BWM-PARENT", bypass_name: str = "BWM-BYPASS-GROUP") -> Tuple[bool, str]:
        """
        Removes all queues generated by BWM and restores FastTrack firewall rules.
        Leaves the router in a clean factory-like state.
        """
        steps = []
        try:
            # 1. Remove individual queues with BWM tags or parented to BWM-PARENT
            await exec_cmd_func(f'/queue simple remove [find parent="{parent_name}"]')
            
            # 2. Remove core BWM queues
            await exec_cmd_func(f'/queue simple remove [find name="{parent_name}"]')
            await exec_cmd_func(f'/queue simple remove [find name="{bypass_name}"]')
            steps.append("Seluruh antrean Simple Queue BWM telah dibersihkan.")

            # 3. Restore FastTrack rule
            ft_ok, ft_msg = await FirewallHelper.restore_fasttrack(exec_cmd_func)
            steps.append(ft_msg)

            return True, "Clean Detach Selesai: " + " ".join(steps)
        except Exception as e:
            return False, f"Clean Detach gagal sebagian: {str(e)}"
